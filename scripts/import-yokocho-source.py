"""Fill the reviewed Yokocho inbox from a digest-pinned original release.

No rendering or network-discovered content is trusted here. Expected output hashes
come from local reviewed exports. Inbox validation and CI follow this step.
"""
from pathlib import Path
import argparse,hashlib,json,os,shutil,subprocess,sys,tempfile,urllib.request,zipfile
ROOT=Path(__file__).resolve().parents[1]
URL='https://github.com/Xenoah/vrcworld_jujo-yokocho/releases/download/v2.19.0/TreeTopYokocho_v2.19.0_checkpoint1_source.zip'
DIGEST='d8699d41f30ff9edd2d172bc12f683fb07a4a6eb1e499fdc5b67c5bbeedf2036'
SIZE=239756388
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
parser=argparse.ArgumentParser();parser.add_argument('--archive',type=Path);args=parser.parse_args()
plan=json.loads((ROOT/'docs/yokocho-import-plan.json').read_text())
with tempfile.TemporaryDirectory(prefix='meshcopia-yokocho-') as temp:
 tmp=Path(temp);archive=args.archive or tmp/'source.zip'
 if not args.archive:
  with urllib.request.urlopen(URL,timeout=120) as response,archive.open('wb') as target:shutil.copyfileobj(response,target)
 assert archive.stat().st_size==SIZE and sha(archive)==DIGEST,'Upstream archive size/digest mismatch'
 needed={'Source/TreeTopYokocho.glb'} | set(plan['upstreamHashes'])
 for item in plan['files']:
  if item.get('upstreamPath'):needed.add(item['upstreamPath'])
 for path in plan['originalTextures']:needed.add(path)
 source=tmp/'TreeTopYokocho'
 with zipfile.ZipFile(archive) as z:
  for relative in sorted(needed):
   assert not relative.startswith('/') and '..' not in Path(relative).parts
   target=source/relative;target.parent.mkdir(parents=True,exist_ok=True)
   with z.open('TreeTopYokocho/'+relative) as src,target.open('wb') as dst:shutil.copyfileobj(src,dst)
 for relative,digest in plan['upstreamHashes'].items():assert sha(source/relative)==digest,relative
 out=tmp/'models';out.mkdir()
 env=dict(os.environ,YOKOCHO_SOURCE_ROOT=str(source),YOKOCHO_OUTPUT=str(out))
 subprocess.run([sys.executable,str(ROOT/'scripts/yokocho/extract-models.py')],env=env,check=True)
 for item in plan['files']:
  target=ROOT/item['destination'];assert str(target.resolve()).startswith(str((ROOT/'_inbox').resolve())+os.sep)
  if item.get('upstreamPath'):src=source/item['upstreamPath']
  elif item.get('modelId'):src=out/item['modelId']/item['modelFile']
  else:
   assert target.is_file() and sha(target)==item['sha256'],str(target)
   continue
  assert sha(src)==item['sha256'],f'Generated byte mismatch: {item["destination"]}'
  target.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(src,target)
print(f'Filled and SHA256-verified {len(plan["files"])} Yokocho source files. Standard inbox import/check remains required.')
